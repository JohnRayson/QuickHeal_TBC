-- Quick Heal Description

QH_LOCALE_DESCRIPTION =
[=[
Wenn aktiviert werden neben jedem Spieler und Gruppenframe Schadensleisten
zu sehen sein. Diese Leisten zeigen den Schaden den ein Spieler in der Gruppe
erhält währenddessen verändert die Leiste ihre Farbe von Grün, zu Gelb, bis zu
Rot bei Tot. In einem Raid werden die Leisten neben jedem Spielernamen angezeigt
und ermöglichen schnelle und einfache Überwachung. Eine Reichweitenüberprüfung
erleichtert es, sich auf Gruppen und Schlachtzugmitglieder in Reichweite zu
konzentrieren.

Mit öffnen der Einstellungen (/QH2 oder zugewiesene Taste) kann der Benutzer
Zauber aus dem Zauberbuch wählen, die auf das Jeweilige Gruppen und
Schlachtzugmitglied gewirkt werden wenn die zugehörige Leiste geklickt wird.
Es können alle Maustasten, so wie Varianten mit Shift, STRG und Alt zugewiesen
werden.

Auch Makros können zugewiesen werden wenn ein Ausrufezeichen (!) als Prefix im
Namen tragen. Damit Makros funktionieren wie du es von ihnen erwartest wenn du
Schadensleisten der Spieler drückst, benutze das Schlüsselwort 'unit' damit
Quick Heal versteht den Zauber auf der Leiste zu wirken. Um den Zauber Erneuerung
zu wirken, würdest du folgendes Makro verwenden. '/cast [target=unit] Erneuerung'.
]=];

